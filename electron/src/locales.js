const LANGUAGES = {
  de: { name: 'Deutsch', locale: 'de-DE', strings: de },
  en: { name: 'English', locale: 'en-US', strings: en },
  es: { name: 'Español', locale: 'es-ES', strings: es },
  fr: { name: 'Français', locale: 'fr-FR', strings: fr },
  tr: { name: 'Türkçe', locale: 'tr-TR', strings: tr },
};

function resolve(setting, systemLocale) {
  if (setting && LANGUAGES[setting]) return setting;
  const sys = (systemLocale || '').slice(0, 2).toLowerCase();
  return LANGUAGES[sys] ? sys : 'en';
}

function translate(lang, key, vars = {}) {
  const text = LANGUAGES[lang]?.strings[key] ?? en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}

module.exports = { LANGUAGES, resolve, translate };
